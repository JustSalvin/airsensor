#!/usr/bin/env python3
"""Renders a 180x180 PNG apple-touch-icon and embeds it as icon_png.h.

Pure stdlib (struct + zlib) - no imaging libraries. iOS ignores SVG
apple-touch-icon links, so we need a real raster PNG.
"""
import pathlib
import struct
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

W = H = 180
BG = (0x14, 0x1b, 0x24)   # background
FG = (0x4f, 0xc9, 0x8f)   # ring + dot
CX = CY = W / 2.0
R_IN, R_OUT = 50, 64      # ring band, distance from center in px
DOT_R = 12                # filled center dot radius


def pixel(x, y):
    dx = x - CX
    dy = y - CY
    d = (dx * dx + dy * dy) ** 0.5
    if d <= DOT_R:
        return FG
    if R_IN <= d <= R_OUT:
        return FG
    return BG


def build_raw_scanlines():
    rows = bytearray()
    for y in range(H):
        rows.append(0)  # filter type 0 (none) for every scanline
        for x in range(W):
            r, g, b = pixel(x + 0.5, y + 0.5)
            rows += bytes((r, g, b))
    return bytes(rows)


def chunk(tag: bytes, data: bytes) -> bytes:
    return (struct.pack(">I", len(data)) + tag + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))


def build_png() -> bytes:
    sig = b"\x89PNG\r\n\x1a\n"
    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)  # 8-bit, RGB, no alpha
    raw = build_raw_scanlines()
    idat = zlib.compress(raw, 9)
    return sig + chunk(b"IHDR", ihdr) + chunk(b"IDAT", idat) + chunk(b"IEND", b"")


def write_header(png: bytes):
    lines = []
    for i in range(0, len(png), 16):
        row = ", ".join(f"0x{b:02x}" for b in png[i:i + 16])
        lines.append("    " + row + ",")
    body = "\n".join(lines)
    header = (
        "// AUTO-GENERATED by dev/make_icon.py - DO NOT EDIT\n"
        "#pragma once\n"
        "#include <stddef.h>\n"
        "static const uint8_t ICON_PNG[] PROGMEM = {\n"
        f"{body}\n"
        "};\n"
        "static const size_t ICON_PNG_LEN = sizeof ICON_PNG;\n"
    )
    (ROOT / "icon_png.h").write_text(header)


def main():
    png = build_png()
    write_header(png)
    (ROOT / "dev" / "icon-preview.png").write_bytes(png)
    print(f"icon_png.h: {len(png)} PNG bytes ({W}x{H})")


if __name__ == "__main__":
    main()
